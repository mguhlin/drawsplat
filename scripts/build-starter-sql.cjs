// Generate the optional empty-install database from the same sources as automatic setup.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {MIGRATION_FILES} = require('../server/mysql-backend/migrate');
const root = path.resolve(__dirname, '..');
const sources = MIGRATION_FILES.map(name => fs.readFileSync(path.join(root, 'server/mysql-backend', name), 'utf8'));
const fingerprint = crypto.createHash('sha256').update(sources.join('\n')).digest('hex');
const sql = `-- DrawSplat starter database v1; schema SHA-256: ${fingerprint}
-- MariaDB 11.8 / MySQL 8.4. Import ONLY into a new, empty database.
-- Select the database in phpMyAdmin first, or pass its name to mariadb/mysql.
-- Stop on any import error. Do not use --force. No accounts or secrets included.
-- Finish /setup afterward to create your administrator and private server settings.
-- Generated by: node scripts/build-starter-sql.cjs
SET NAMES utf8mb4;
SET time_zone = '+00:00';
CREATE TABLE drawsplat_migrations (name VARCHAR(190) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
` + MIGRATION_FILES.map((name, i) => `\n-- Source: ${name}\n` + sources[i].replace(/CREATE TABLE IF NOT EXISTS/g, 'CREATE TABLE') + `\nINSERT INTO drawsplat_migrations (name) VALUES ('${name}');\n`).join('');
const target = path.join(root, 'downloads/drawsplat-starter.sql');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== sql) {
    console.error('Starter SQL is stale. Run node scripts/build-starter-sql.cjs');
    process.exitCode = 1;
  } else console.log('Starter SQL matches all current migrations.');
} else {
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, sql);
  console.log('Generated downloads/drawsplat-starter.sql');
}
